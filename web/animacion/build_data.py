"""Regenerate data.js for the pitch animation from the real engine output.

Usage (from web/animacion/):   python build_data.py
Re-run it whenever the backend rules or the example field change, then reload the animation.
Nothing here is invented: failures come from POST /recomendar, rainfall from data/nasa_power/durango_annual.csv.
"""
import csv, io, json, os, re, sys, urllib.request
from datetime import datetime, timezone

# ── DATOS ──
API_URL = "https://rotahalcon.onrender.com"          # or http://localhost:8000
REQUEST = {"lat": 24.02, "lon": -104.65, "suelo": "franco", "cultivos_previos": ["frijol", "frijol"],
           "prioridades": {"agua": 0.4, "suelo": 0.3, "ingreso": 0.2, "riesgo": 0.1},
           "escenario": {"lluvia_pct": 0, "temp_c": 0}}
PRIORITIES_B = {"agua": 0.7, "suelo": 0.1, "ingreso": 0.1, "riesgo": 0.1}   # "water first": used by the sliders scene
HERE = os.path.dirname(os.path.abspath(__file__))
RAIN_CSV = os.path.join(HERE, "..", "..", "data", "nasa_power", "durango_annual.csv")
OUT = os.path.join(HERE, "data.js")
# ── FIN DATOS ──

def recomendar(body):
    req = urllib.request.Request(API_URL + "/recomendar", data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)

rec = recomendar(REQUEST)
rec_b = recomendar(dict(REQUEST, prioridades=PRIORITIES_B))      # same field, different priorities
score_b = {e["id"]: e["puntaje"] for e in rec_b["estrategias"]}

rain = {}
with io.open(RAIN_CSV, encoding="utf-8") as f:
    for row in csv.DictReader(f):
        rain[int(row["year"])] = float(row["PRECTOTCORR_sum_mm"])

years = [a["anio"] for a in rec["estrategias"][0]["anios"]]
out = {
    "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
    "source": API_URL + "/recomendar",
    "request": REQUEST,
    "prioridades_b": PRIORITIES_B,
    "years": years,
    "rain_mm": [rain.get(y) for y in years],          # NASA POWER PRECTOTCORR annual sum
    "estrategias": [],
    "sensor": rec.get("sensor"),
    "calibracion": rec.get("calibracion"),
}
for e in rec["estrategias"]:
    bad = [a for a in e["anios"] if not a["ok"]]
    out["estrategias"].append({
        "id": e["id"], "es_actual": bool(e.get("es_actual")), "ciclos": e["ciclos"],
        "semaforo": e["semaforo"], "puntaje": e["puntaje"], "puntaje_b": score_b.get(e["id"]), "resiliencia": e["resiliencia"],
        "peor_anio": e["peor_anio"],
        "fails": [a["anio"] for a in bad],
        "by_drought": sum(1 for a in bad if a.get("motivo", "").startswith("drought")),
        "by_frost": sum(1 for a in bad if a.get("motivo", "").startswith("frost")),
        "motivos": {str(a["anio"]): a.get("motivo", "") for a in bad},
    })

with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by build_data.py – do not edit by hand. Real engine output + NASA POWER rainfall.\n")
    f.write("window.ROTA_DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")

print("wrote", OUT)
for e in out["estrategias"]:
    print(" ", e["id"], e["ciclos"], "fails", len(e["fails"]), "of", len(years), "score", e["puntaje"], "worst", e["peor_anio"]["anio"])
